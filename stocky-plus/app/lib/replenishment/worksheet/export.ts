/**
 * A worksheet as a spreadsheet: one row per variant with the figures the
 * screen shows and the ones in each row's detail.
 */
import { revenuePerDay, STOCK_STATUS_LABELS, WARNING_LABELS } from "./describe";
import type { WorksheetLine } from "./store.server";

export const WORKSHEET_CSV_HEADERS = [
  "Product",
  "Variant",
  "SKU",
  "Barcode",
  "Vendor",
  "Product type",
  "Supplier",
  "Supplier SKU",
  "Available",
  "On hand",
  "Committed",
  "Incoming",
  "Net units sold",
  "Orders",
  "Net sales",
  "Net sales per day",
  "Units per day",
  "ABC class",
  "Days of stock",
  "Runs out around",
  "Stock status",
  "Lead time (days)",
  "Reorder point",
  "Minimum",
  "Shelf limit",
  "Supplier minimum order",
  "Pack size",
  "Quantity before supplier rules",
  "Suggested quantity",
  "Order quantity",
  "Edited",
  "Price",
  "Price currency",
  "Shopify unit cost",
  "Shopify unit cost currency",
  "Supplier cost",
  "Supplier cost currency",
  "Warnings",
  "Purchase order",
] as const;

type Cell = string | number | null;

/** `salesDays` is the length of the worksheet's sales period, when known. */
export function worksheetCsvRow(line: WorksheetLine, salesDays: number | null): Cell[] {
  return [
    line.productTitle,
    line.variantTitle === "Default Title" ? "" : line.variantTitle,
    line.sku,
    line.barcode,
    line.vendor,
    line.productType,
    line.supplierName,
    line.vendorSku,
    line.availableQuantity,
    line.onHandQuantity,
    line.committedQuantity,
    line.incomingQuantity,
    line.netUnits,
    line.distinctOrders,
    line.revenueAmount,
    revenuePerDay(line.revenueAmount, salesDays),
    line.unitsPerDay,
    line.abcClass,
    line.daysOfStock,
    line.depletionDate,
    STOCK_STATUS_LABELS[line.stockStatus],
    line.leadTimeDays,
    line.reorderPoint,
    line.detail.levels.minimumQuantity,
    line.detail.levels.shelfLimitQuantity,
    line.minimumOrderQuantity,
    line.packSize,
    line.parityQuantity,
    line.suggestedQuantity,
    line.orderQuantity,
    line.finalQuantity == null ? "No" : "Yes",
    line.priceAmount,
    line.priceCurrencyCode,
    line.unitCostAmount,
    line.unitCostCurrencyCode,
    line.supplierCostAmount,
    line.supplierCostCurrencyCode,
    line.warningCodes.map((code) => WARNING_LABELS[code] ?? code).join("; "),
    line.purchaseOrderNumber,
  ];
}
